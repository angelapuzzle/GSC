package com.gsc.gsc.dto;

public class AsignacionPcDTO {
    private String tipoAccion;
    private String documento;
    private String equipoSeleccionado;

    public String getTipoAccion() { return tipoAccion; }
    public void setTipoAccion(String tipoAccion) { this.tipoAccion = tipoAccion; }

    public String getDocumento() { return documento; }
    public void setDocumento(String documento) { this.documento = documento; }

    public String getEquipoSeleccionado() { return equipoSeleccionado; }
    public void setEquipoSeleccionado(String equipoSeleccionado) { this.equipoSeleccionado = equipoSeleccionado; }
}
